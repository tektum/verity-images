#!/bin/sh
set -eu

image=${1:?usage: test.sh IMAGE}
expected_version=$(sed -n 's/^    - mockery=\([0-9][0-9.]*\)-r[0-9]*$/\1/p' \
  "$(dirname "$0")/../apko.yaml")
[ -n "$expected_version" ] || { printf '%s\n' 'mockery package pin not found' >&2; exit 1; }
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT HUP INT TERM

fail() {
  printf 'FAIL: %s\n' "$1" >&2
  exit 1
}

# Everything runs offline: the module has no dependencies and the matryer
# template generates mocks that need only the standard library.
run() {
  timeout 120 docker run --rm --network none -v "$work/mod:/work" "$@"
}

user=$(docker image inspect -f '{{.Config.User}}' "$image")
[ "$user" = 65532 ] || fail "image user is $user, want 65532"
entrypoint=$(docker image inspect -f '{{json .Config.Entrypoint}} {{json .Config.Cmd}}' "$image")
[ "$entrypoint" = '["/usr/bin/mockery"] null' ] || fail "unexpected entrypoint: $entrypoint"
workdir=$(docker image inspect -f '{{.Config.WorkingDir}}' "$image")
[ "$workdir" = /work ] || fail "unexpected working directory: $workdir"

mkdir -p "$work/mod/shapes"
version=$(run "$image" version 2>&1 | tail -n 1)
[ "$version" = "v$expected_version" ] || fail "unexpected version '$version', want v$expected_version"
run --entrypoint go "$image" version >"$work/go.txt" 2>&1 ||
  { cat "$work/go.txt" >&2; fail 'the bundled Go toolchain does not run'; }
grep -E '^go version go1\.[0-9]+(\.[0-9]+)? linux/' "$work/go.txt" >/dev/null ||
  { cat "$work/go.txt" >&2; fail 'unexpected go version output'; }

printf 'module example.test/smoke\n\ngo 1.24\n' >"$work/mod/go.mod"
cat >"$work/mod/shapes/shapes.go" <<'EOF'
package shapes

// Shape is mocked by the smoke test.
type Shape interface {
	Area(scale int) (float64, error)
	Name() string
}

// Describe classifies a Shape by its area at scale 2.
func Describe(s Shape) string {
	a, err := s.Area(2)
	if err != nil {
		return s.Name() + ": " + err.Error()
	}
	if a > 10 {
		return s.Name() + ": large"
	}
	return s.Name() + ": small"
}
EOF
cat >"$work/mod/shapes/shapes_test.go" <<'EOF'
package shapes

import (
	"errors"
	"testing"
)

func TestDescribeWithGeneratedMock(t *testing.T) {
	m := &MockShape{
		AreaFunc: func(scale int) (float64, error) { return float64(scale) * 6, nil },
		NameFunc: func() string { return "square" },
	}
	if got := Describe(m); got != "square: large" {
		t.Fatalf("Describe = %q", got)
	}
	if calls := m.AreaCalls(); len(calls) != 1 || calls[0].Scale != 2 {
		t.Fatalf("AreaCalls = %+v", calls)
	}
	m.AreaFunc = func(int) (float64, error) { return 0, errors.New("no area") }
	if got := Describe(m); got != "square: no area" {
		t.Fatalf("Describe = %q", got)
	}
	if n := len(m.NameCalls()); n != 2 {
		t.Fatalf("NameCalls = %d", n)
	}
}
EOF
cat >"$work/mod/.mockery.yml" <<'EOF'
template: matryer
packages:
  example.test/smoke/shapes:
    interfaces:
      Shape:
EOF
cat >"$work/mod/missing.yml" <<'EOF'
template: matryer
packages:
  example.test/smoke/shapes:
    interfaces:
      Missing:
EOF
chmod -R a+rwX "$work/mod"

run "$image" >"$work/generate.txt" 2>&1 || { cat "$work/generate.txt" >&2; fail 'mockery generation failed'; }
mock="$work/mod/shapes/mocks_test.go"
[ -s "$mock" ] || { cat "$work/generate.txt" >&2; fail 'mockery did not write shapes/mocks_test.go'; }
sed -n 1p "$mock" | grep -Fx '// Code generated by mockery; DO NOT EDIT.' >/dev/null ||
  fail 'generated file lacks the mockery header'
grep -Fx 'var _ Shape = &MockShape{}' "$mock" >/dev/null || fail 'generated mock does not assert it implements Shape'

# The generated mock compiles and behaves as a mock under the bundled toolchain.
run --entrypoint go "$image" test ./... >"$work/gotest.txt" 2>&1 ||
  { cat "$work/gotest.txt" >&2; fail 'go test with the generated mock failed'; }
grep -E '^ok[[:space:]]+example\.test/smoke/shapes' "$work/gotest.txt" >/dev/null ||
  { cat "$work/gotest.txt" >&2; fail 'go test did not run the shapes package'; }

if run "$image" --config /work/missing.yml >"$work/missing.txt" 2>&1; then
  fail 'a missing interface was accepted'
fi
grep -F 'interface not found in source' "$work/missing.txt" >/dev/null ||
  { cat "$work/missing.txt" >&2; fail 'missing interface error does not say so'; }
if run "$image" --config /work/absent.yml >"$work/absent.txt" 2>&1; then
  fail 'a missing config file was accepted'
fi
grep -F 'open /work/absent.yml: no such file or directory' "$work/absent.txt" >/dev/null ||
  { cat "$work/absent.txt" >&2; fail 'missing config error does not name the file'; }
if run "$image" --no-such-flag >"$work/flag.txt" 2>&1; then
  fail 'unknown flag was accepted'
fi
grep -F 'no-such-flag' "$work/flag.txt" >/dev/null ||
  { cat "$work/flag.txt" >&2; fail 'unknown flag error does not name the flag'; }

printf '%s\n' "mockery $expected_version smoke test passed"
