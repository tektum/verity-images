#!/bin/sh
set -eu

image=${1:?usage: test.sh IMAGE}
work=$(mktemp -d)
# Run as the host user so files created in the bind mount stay removable.
run_as=$(id -u):$(id -g)

cleanup() {
  rm -rf "$work"
}
trap cleanup EXIT INT TERM

fail() {
  printf '%s\n' "$1" >&2
  exit 1
}

run() {
  docker run --rm --network none --user "$run_as" -e HOME=/src -v "$work:/src" "$@"
}

test "$(docker image inspect --format '{{.Config.User}}' "$image")" = 65532 ||
  fail 'unexpected OCI user'
test "$(docker image inspect --format '{{json .Config.Entrypoint}}' "$image")" = \
  '["/usr/bin/goreleaser"]' || fail 'unexpected entrypoint'

version=$(docker run --rm --network none --read-only "$image" --version) ||
  fail 'goreleaser --version failed'
printf '%s\n' "$version" | grep -E 'GitVersion:[[:space:]]+[0-9]+\.[0-9]+\.[0-9]+' >/dev/null ||
  fail 'goreleaser version output has no GitVersion'

# Negative: an unknown flag must exit non-zero.
if docker run --rm --network none --read-only "$image" --no-such-flag >/dev/null 2>&1; then
  fail 'unknown flag unexpectedly succeeded'
fi

# Create a config with init, then validate it. goreleaser check needs a git repo with a remote.
run --entrypoint /usr/bin/git "$image" init -q -b main . || fail 'git init failed'
run --entrypoint /usr/bin/git "$image" config user.email smoke@example.com || fail 'git config failed'
run --entrypoint /usr/bin/git "$image" config user.name smoke || fail 'git config failed'
run --entrypoint /usr/bin/git "$image" remote add origin https://github.com/example/example.git ||
  fail 'git remote failed'
run "$image" init >/dev/null 2>&1 || fail 'goreleaser init failed'
test -f "$work/.goreleaser.yaml" || fail 'goreleaser init did not write .goreleaser.yaml'
run "$image" check >"$work/check.log" 2>&1 || { cat "$work/check.log" >&2; fail 'goreleaser check failed on the init config'; }
grep -F 'configuration file(s) validated' "$work/check.log" >/dev/null || fail 'goreleaser check did not report a valid config'

# Negative: a config that is not valid for goreleaser must fail the check.
printf '%s\n' 'version: 2' 'builds: not-a-list' >"$work/.goreleaser.yaml"
if run "$image" check >/dev/null 2>&1; then
  fail 'invalid config unexpectedly passed goreleaser check'
fi

# A real build: goreleaser drives the bundled Go toolchain on a small module, offline.
mkdir -p "$work/app"
printf '%s\n' 'module example.com/smoke' '' 'go 1.22' >"$work/app/go.mod"
cat >"$work/app/main.go" <<'GO'
package main

import "fmt"

func main() { fmt.Println("smoke-built") }
GO
cat >"$work/app/.goreleaser.yaml" <<'YAML'
version: 2
project_name: smoke
builds:
  - main: .
    binary: smoke
    env: [CGO_ENABLED=0]
    goos: [linux]
    goarch: [amd64, arm64]
YAML
docker run --rm --network none --user "$run_as" -e HOME=/src -v "$work:/src" -w /src/app --entrypoint /usr/bin/git \
  "$image" init -q -b main . || fail 'git init in the Go module failed'
docker run --rm --network none --user "$run_as" -e HOME=/src -v "$work:/src" -w /src/app --entrypoint /usr/bin/git \
  "$image" -c user.email=smoke@example.com -c user.name=smoke add -A || fail 'git add failed'
docker run --rm --network none --user "$run_as" -e HOME=/src -v "$work:/src" -w /src/app --entrypoint /usr/bin/git \
  "$image" -c user.email=smoke@example.com -c user.name=smoke commit -q -m smoke || fail 'git commit failed'
docker run --rm --network none --user "$run_as" -e HOME=/src -e GOCACHE=/tmp/gocache -e GOPATH=/tmp/gopath \
  --tmpfs /tmp:exec -v "$work:/src" -w /src/app "$image" \
  build --snapshot --single-target --clean >"$work/build.log" 2>&1 ||
  { cat "$work/build.log" >&2; fail 'goreleaser build failed'; }
built=$(find "$work/app/dist" -type f -name smoke | head -n 1)
test -x "$built" || fail 'goreleaser build produced no binary'
rel=${built#"$work"/}
test "$(docker run --rm --network none --user "$run_as" -v "$work:/src" --entrypoint "/src/$rel" "$image")" = smoke-built ||
  fail 'built binary prints the wrong output'

# The JSON schema and shell completions are generated by the binary itself.
run "$image" jsonschema >"$work/schema.json" 2>/dev/null || fail 'goreleaser jsonschema failed'
grep -F 'json-schema.org' "$work/schema.json" >/dev/null || fail 'jsonschema output is not a JSON schema'
run "$image" completion bash >"$work/completion.bash" 2>/dev/null || fail 'goreleaser completion failed'
grep -F 'goreleaser' "$work/completion.bash" >/dev/null || fail 'bash completion is missing goreleaser'

printf 'SMOKE PASS image=%s\n' "$image"
